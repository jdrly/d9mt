#!/usr/bin/env python3
"""Cut #62's null-texture selection out of the backend sources for test/native/null_kind_test.cpp.

From mtl_context_impl.h: the kNullCubeFirstSlot and kNull3DFirstSlot constants and
nullTextureId()'s whole definition.
From mtl_context_transfer.cpp: the statements that pick the argument table's texture slots to
rewrite (fnId .. texMask). Each anchor must occur exactly once, else exit 2; the cut text is
written unchanged into <out>/null_kind_extract.h, so the test compiles the production statements.
The header also gets NullKindContextPlanted: the same method with the first 3D slot one too high,
a wrong mapping the test must catch.
    null_kind_extract.py <mtl_context_impl.h> <mtl_context_transfer.cpp> <out dir>
"""
import os, sys

def fail(msg):
    print(f"null_kind_extract: {msg}", file=sys.stderr)
    sys.exit(2)

def once(text, anchor, what):
    n = text.count(anchor)
    if n != 1:
        fail(f"{what}: anchor {anchor!r} found {n} times (want 1)")
    return text.index(anchor)

def braced(text, start, what):
    i = text.index('{', start)
    depth = 0
    for j in range(i, len(text)):
        if text[j] == '{': depth += 1
        elif text[j] == '}':
            depth -= 1
            if depth == 0:
                return text[start:j + 1]
    fail(f"{what}: unbalanced braces")

impl_path, xfer_path, out = sys.argv[1:4]
impl = open(impl_path).read()
xfer = open(xfer_path).read()

c = once(impl, 'static constexpr uint32_t kNullCubeFirstSlot', 'kNullCubeFirstSlot')
const_line = impl[c:impl.index('\n', c)].strip()
c3 = once(impl, 'static constexpr uint32_t kNull3DFirstSlot', 'kNull3DFirstSlot')
const3_line = impl[c3:impl.index('\n', c3)].strip()
m = once(impl, 'uint64_t nullTextureId(uint32_t stage, uint32_t slot, const MtlShaderFunction* fn = nullptr) const {',
         'nullTextureId')
method = braced(impl, m, 'nullTextureId')
if 'kNull3DFirstSlot' not in method:
    fail('nullTextureId: expected kNull3DFirstSlot in the cut')
planted = method.replace('kNull3DFirstSlot', 'kPlanted3DFirstSlot')

a = once(xfer, 'const uint64_t fnId = fn != nullptr ? uint64_t(fn->library) : 0u;', 'texMask start')
end_anchor = '& ((1u << b.textures.size()) - 1u);'
e = xfer.index(end_anchor, a)
mask_block = xfer[a:e + len(end_anchor)]
if 'texMask' not in mask_block or 'tableFnId' not in mask_block:
    fail('texMask block: expected texMask and tableFnId in the cut')

with open(os.path.join(out, 'null_kind_extract.h'), 'w') as f:
    f.write('// generated by null_kind_extract.py from ' + os.path.basename(impl_path) + ' and '
            + os.path.basename(xfer_path) + '\n')
    ids = '  uint64_t m_null2DId = 0x2D, m_nullCubeId = 0xCB, m_null3DId = 0x3D;\n  '
    f.write('struct NullKindContext {\n  ' + const_line + '\n  ' + const3_line + '\n' + ids
            + method + '\n};\n\n')
    f.write('// not production: nullTextureId() with a wrong first 3D slot, for the test\'s negative case\n'
            'struct NullKindContextPlanted {\n  ' + const_line + '\n'
            '  static constexpr uint32_t kPlanted3DFirstSlot = 17u;\n' + ids
            + planted + '\n};\n\n')
    f.write('template <typename Bindings, typename FnPtr>\n'
            'inline uint32_t tableTextureMask(Bindings& b, const FnPtr& fn) {\n  '
            + mask_block + '\n  return texMask;\n}\n')
print('null_kind_extract: ok')
